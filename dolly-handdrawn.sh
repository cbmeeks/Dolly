#!/usr/bin/env bash
# Renders a hand-drawn ASCII drawing of Dolly Parton's face and big, teased blonde hair.
# Hair is drawn with @ % ~ and lips with =; on a color terminal they are
# tinted blonde and red. Piped output stays plain text.
set -euo pipefail

art() {
cat <<'EOF'
                 @@@@@@@@@@@@@@@
            @@@@@%%%%@@@@@%%%%@@@@@
         @@@%%@@@~~~~~~@@@~~~~~~@@@%%@@
       @@%%@@~~~~~~~~~~~@@~~~~~~~~~~~@@%%@@
     @@%@@~~~~~~~~~~~~~~@@~~~~~~~~~~~~~~@@%@@
    @%@@~~~~~~~~~~~~~~~~@@~~~~~~~~~~~~~~~~@@%@
   @%@~~~~~~~~~~_.-""""""""""-._~~~~~~~~~~~~@%@
  @%@@~~~~~~~~/~~~~~~~~~~~~~~~~\~~~~~~~~~~~@@%@
  @%@~~~~~~~~/   ___        ___   \~~~~~~~~~@%@
  @%@@~~~~~~|   ~~~~~~    ~~~~~~   |~~~~~~~@@%@
  @%@@~~~~~~|  \ \|/ /  \ \|/ /  |~~~~~~~@@%@
   @%@~~~~~~|   (  o  )  (  o  )   |~~~~~~@%@
   @%@@~~~~~|     `---'    `---'    |~~~~~@@%@
    @%@~~~~~|          /|\          |~~~~~@%@
    @%@@~~~~|         ( . )   .     |~~~~@@%@
     @%@~~~~ \         `-'         / ~~~~@%@
     @%@@~~~~ \     .--------.     / ~~~@@%@
      @%@~~~~~ \   (==========)   / ~~~~@%@
      @%@@~~~~~ `.  `--====--'  .' ~~~~@@%@
       @%@@~~~~~~ `-.        .-' ~~~~~@@%@
        @%@@~~~~~~~~ `------' ~~~~~~~~@@%@
         @%@@@~~~~~~~~~~~~~~~~~~~~~@@@%@
          @%%@@@~~~~~~~~~~~~~~~~@@@%%@
           @@%%@@@~~~~~~~~~~~@@@@%%@@
             @@@%%%@@@@@@@@%%%@@@
                 @@@@@@@@@@@
EOF
}

if [[ -t 1 ]]; then
  yellow=$'\e[93m'
  red=$'\e[91m'
  reset=$'\e[0m'
  art | sed -e "s/[@%~]\+/${yellow}&${reset}/g" \
            -e "s/=\+/${red}&${reset}/g"
else
  art
fi

echo "              ~ Dolly Parton ~"
